#!/usr/bin/env python3
"""Generate the Bob pointer skills in .bob/skills/ from the canonical .agents/skills/.

IBM Bob discovers project skills in .bob/skills/<name>/SKILL.md. The canonical skills live
in .agents/skills/<name>/SKILL.md so that other agents can use them too. Each pointer copies
the canonical frontmatter (so activation works the same) and tells Bob to read the canonical
file.

Usage:
    python scripts/sync_bob_skills.py          # (re)generate the pointers
    python scripts/sync_bob_skills.py --check  # exit 1 if any pointer is missing or stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANONICAL_DIR = ROOT / ".agents" / "skills"
BOB_DIR = ROOT / ".bob" / "skills"
FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)

POINTER_BODY = """
# {name} (Bob pointer skill)

The canonical skill lives in `.agents/skills/{name}/SKILL.md`, which is shared with other
agents. Read that file now with the read tool and follow it exactly. Resolve the relative
paths it mentions (for example `best-practices/...` or `examples/...`) against
`.agents/skills/{name}/`.

Do not edit this pointer. It is generated by `scripts/sync_bob_skills.py`; edit the
canonical file and re-run that script.
"""


POINTER_MARKER = "# {name} (Bob pointer skill)"


def canonical_skills() -> list[Path]:
    return sorted(p for p in CANONICAL_DIR.glob("*/SKILL.md"))


def render_pointer(skill_md: Path) -> str:
    text = skill_md.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise SystemExit(f"{skill_md}: missing YAML frontmatter")
    name = skill_md.parent.name
    return f"---\n{match.group(1)}\n---\n" + POINTER_BODY.format(name=name)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    expected_names = set()
    for skill_md in canonical_skills():
        name = skill_md.parent.name
        expected_names.add(name)
        target = BOB_DIR / name / "SKILL.md"
        content = render_pointer(skill_md)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == content:
            continue
        if check:
            stale.append(target.relative_to(ROOT).as_posix())
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
            print(f"updated {target.relative_to(ROOT).as_posix()}")

    # Only generated pointers can be orphans. Standalone Bob skills (for example the
    # oracle-aix-setup installer) have no canonical skill and are left alone.
    orphans = [
        p.relative_to(ROOT).as_posix()
        for p in BOB_DIR.glob("*/SKILL.md")
        if p.parent.name not in expected_names
        and POINTER_MARKER.format(name=p.parent.name) in p.read_text(encoding="utf-8")
    ]
    if check:
        for path in stale:
            print(f"stale or missing Bob pointer skill: {path} (run scripts/sync_bob_skills.py)")
        for path in orphans:
            print(f"orphan Bob pointer skill without canonical skill: {path}")
        return 1 if stale or orphans else 0
    for path in orphans:
        print(f"warning: orphan pointer {path} (no matching .agents/skills entry)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
